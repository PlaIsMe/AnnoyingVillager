    private static final RigAnimationId[] VALUES = values();

    public int networkId() { return this.ordinal(); }

    public boolean isAttack() { return RigAnimationSpecs.isAttack(this); }

    public boolean isMountedAttack() { return this.name().contains("MOUNT_ATTACK"); }

    public boolean isRolling() { return isRollAnimation() || isStepAnimation(); }

    public boolean isUtilityAnimation() { return !isAttack() && !isRolling(); }

    public boolean isShieldGuardAnimation() {
        return this == SHIELD_OFFHAND || this == SHIELD_MAINHAND || this == AEGIS_HEROBRINE_GUARD;
    }

    public boolean isShieldGuardHitAnimation() {
        return this == BLOCK_SHIELD_OFFHAND || this == BLOCK_SHIELD_MAINHAND;
    }

    public boolean isBowAnimation() { return isBowAimAnimation() || isBowShotAnimation(); }

    public boolean isBowAimAnimation() { return this.name().startsWith("BOW_AIM_"); }

    public boolean isBowShotAnimation() { return this.name().startsWith("BOW_SHOT_"); }

    public boolean isRollAnimation() {
        String name = this.name();
        return name.startsWith("ROLL_") || name.contains("_ROLL");
    }

    public boolean isStepAnimation() {
        String name = this.name();
        return name.startsWith("STEP_") || name.contains("_STEP_");
    }

    public static RigAnimationId fromNetworkId(int networkId) {
        if (networkId < 0 || networkId >= VALUES.length) return BASIC_ATTACK1;
        return VALUES[networkId];
    }
